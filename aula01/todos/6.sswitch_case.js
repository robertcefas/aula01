//Switch - Case

const opcao = 3;

switch (opcao) {
    case 1:
        console.log("Opção 1 ");
        break;
    case 2:
        console.log("Opção 2 ");
        break;
    case 3:
        console.log("Opção 3 "); //alt shift e seta para baixo para copiar a linha
        break; 
    case 4:
        console.log("Opção 4 "); //control de pra selecionar a opção
        break;
    case 5:
        console.log("Opção 5 ");
        break;
    default:
        console.log("Opção inválida"); //alt e sertar para selecionar a opção
        break;
}